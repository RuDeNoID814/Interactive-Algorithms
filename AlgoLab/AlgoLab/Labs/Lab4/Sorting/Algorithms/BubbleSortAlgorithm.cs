namespace AlgoLab.Labs.Lab4.Sorting;

/// <summary>
/// Сортировка пузырьком с ранним выходом («улучшенный пузырёк»).
/// </summary>
/// <remarks>
/// Идея: многократно проходим массив слева направо и меняем местами соседей,
/// стоящих в неправильном порядке. За один проход самый большой элемент
/// «всплывает» в конец, поэтому каждый следующий проход можно делать короче.
/// <para>
/// Улучшение: если за целый проход не было ни одного обмена, массив уже
/// отсортирован — работу можно прекращать досрочно. Благодаря этому на почти
/// отсортированных данных алгоритм работает за O(n) вместо O(n²).
/// </para>
/// <para>
/// Устойчивость: обмен выполняется только при строгом неравенстве
/// (<c>a[j] &gt; a[j+1]</c>), равные элементы не переставляются — сортировка устойчива.
/// </para>
/// </remarks>
public static class BubbleSortAlgorithm
{
    /// <summary>Выполняет сортировку, записывая каждый шаг в трассировщик.</summary>
    public static void Run(SortTracer tracer)
    {
        int n = tracer.Length;

        if (n < 2)
        {
            tracer.MarkAllSorted("Массив из одного элемента уже упорядочен.");
            return;
        }

        // Внешний цикл: номер прохода. После k-го прохода последние k элементов
        // стоят на своих окончательных местах, поэтому их уже не трогаем.
        for (int pass = 0; pass < n - 1; pass++)
        {
            bool swapped = false;

            // Активный участок — ещё не отсортированная часть массива.
            tracer.SetRange(0, n - 1 - pass);
            tracer.Note($"Проход {pass + 1}: идём слева направо по участку из {n - pass} элементов.");

            // Внутренний цикл: сравниваем пары соседей (j, j+1).
            for (int j = 0; j < n - 1 - pass; j++)
            {
                // Сообщение собираем до сравнения, чтобы в тексте были актуальные значения.
                string question = $"Сравниваем соседей на позициях {j} и {j + 1}: " +
                                  $"{tracer.ValueAt(j)} и {tracer.ValueAt(j + 1)}.";

                if (tracer.IsGreater(j, j + 1, question))
                {
                    // Левый больше правого — порядок неправильный, меняем их местами.
                    string swapMessage = $"{tracer.ValueAt(j)} > {tracer.ValueAt(j + 1)} — " +
                                         "меняем местами, чтобы большее число шло правее.";

                    tracer.Swap(j, j + 1, swapMessage);
                    swapped = true;
                }
            }

            // После прохода самый большой элемент участка встал в его конец.
            int settled = n - 1 - pass;
            tracer.MarkSorted(settled, $"Элемент {tracer.ValueAt(settled)} занял окончательное место на позиции {settled}.");
            tracer.ClearRange();

            // Ранний выход: обменов не было — массив уже упорядочен.
            if (!swapped)
            {
                tracer.Note("За весь проход не было ни одного обмена — массив уже отсортирован. Завершаем досрочно.");
                break;
            }
        }

        tracer.MarkAllSorted("Готово! Все элементы стоят по возрастанию.");
    }

    /// <summary>
    /// Быстрая версия без трассировки — для замеров времени.
    /// Код повторяет учебный алгоритм, но не пишет шаги.
    /// </summary>
    public static void Sort(int[] data)
    {
        int n = data.Length;

        for (int pass = 0; pass < n - 1; pass++)
        {
            bool swapped = false;

            for (int j = 0; j < n - 1 - pass; j++)
            {
                if (data[j] > data[j + 1])
                {
                    (data[j], data[j + 1]) = (data[j + 1], data[j]);
                    swapped = true;
                }
            }

            if (!swapped) break;
        }
    }
}
