namespace AlgoLab.Labs.Lab4.Sorting;

/// <summary>
/// Сортировка простыми вставками.
/// </summary>
/// <remarks>
/// Идея: как раскладывают карты в руке. Массив условно делится на «отсортированную
/// левую часть» и «оставшуюся правую». На каждом шаге берём первый элемент правой
/// части («ключ», держим его в руке), освобождаем позицию и сдвигаем вправо все
/// элементы левой части, которые больше ключа. Как только слева оказался элемент
/// не больше ключа, вставляем ключ на освободившееся место.
/// <para>
/// Сложность: внешний цикл — n−1 шаг, внутренний сдвиг в худшем случае — до n
/// сравнений, итого O(n²). На почти отсортированных данных внутренний цикл
/// почти сразу останавливается, поэтому лучший случай — O(n).
/// </para>
/// <para>
/// Устойчивость: условие сдвига строгое (<c>ключ &lt; a[j]</c>), поэтому равные
/// элементы сохраняют исходный порядок — сортировка устойчива.
/// </para>
/// </remarks>
public static class InsertionSortAlgorithm
{
    /// <summary>Выполняет сортировку, записывая каждый шаг в трассировщик.</summary>
    public static void Run(SortTracer tracer)
    {
        int n = tracer.Length;

        if (n < 2)
        {
            tracer.MarkAllSorted("Массив из одного элемента уже упорядочен.");
            return;
        }

        tracer.Note("Считаем, что первый элемент уже образует отсортированную часть. Дальше расширяем её вправо.");

        // i — индекс первого элемента неотсортированной части.
        for (int i = 1; i < n; i++)
        {
            // Активный участок: отсортированная часть плюс текущий ключ.
            tracer.SetRange(0, i);

            int key = tracer.ValueAt(i);

            // Берём ключ «в руку»: в массиве на позиции i образуется «дырка».
            tracer.Hold(i, $"Берём элемент {key} с позиции {i} «в руку» и ищем, куда его вставить.");

            int j = i - 1;

            // Идём влево и сдвигаем всё, что больше ключа.
            while (j >= 0)
            {
                string question = $"Сравниваем ключ {key} с элементом {tracer.ValueAt(j)} на позиции {j}.";

                if (!tracer.HeldIsSmaller(j, question))
                {
                    // Слева уже стоит элемент не больше ключа — место найдено.
                    break;
                }

                // Элемент больше ключа — освобождаем место, сдвигая его вправо.
                string shiftMessage = $"{tracer.ValueAt(j)} больше ключа {key} — сдвигаем его на позицию {j + 1}.";

                tracer.Shift(j, j + 1, shiftMessage);
                j--;
            }

            // Ключ встаёт в освободившееся место. Если сдвигов не было,
            // он уже стоит правильно — перемещение не засчитываем.
            int target = j + 1;

            if (target == i)
            {
                tracer.ReleaseHeld($"Ключ {key} уже больше всех элементов слева — оставляем его на позиции {i}.");
            }
            else
            {
                tracer.PlaceHeld(target,
                    $"Вставляем ключ {key} на позицию {target}: слева от него элементы не больше, справа — больше.");
            }

            tracer.ClearRange();
        }

        tracer.MarkAllSorted("Готово! Каждый элемент побывал ключом, массив упорядочен.");
    }

    /// <summary>
    /// Быстрая версия без трассировки — для замеров времени.
    /// </summary>
    public static void Sort(int[] data)
    {
        for (int i = 1; i < data.Length; i++)
        {
            int key = data[i];
            int j = i - 1;

            while (j >= 0 && data[j] > key)
            {
                data[j + 1] = data[j];
                j--;
            }

            data[j + 1] = key;
        }
    }
}
