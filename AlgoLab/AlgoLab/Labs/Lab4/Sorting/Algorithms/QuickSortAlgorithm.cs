namespace AlgoLab.Labs.Lab4.Sorting;

/// <summary>
/// Быстрая сортировка Хоара (разделение по Хоару, схема с двумя встречными указателями).
/// </summary>
/// <remarks>
/// Идея: выбираем опорный элемент, затем двумя указателями идём навстречу друг другу.
/// Левый указатель ищет элемент, который не меньше опорного, правый — который не больше.
/// Найденную пару меняем местами. Когда указатели встретились, массив распался на две
/// части: слева — не больше опорного, справа — не меньше. Каждую часть сортируем так же.
/// <para>
/// Отличие от схемы Ломуто (она использована в демонстрации лабораторной №1):
/// Хоар выполняет в среднем в три раза меньше обменов, потому что меняет местами сразу
/// найденную «неправильную» пару, а не тащит опорный элемент через весь массив.
/// Опорный элемент при этом не обязан встать точно в середину — он лишь делит массив
/// на две части, поэтому позиция раздела возвращается по правому указателю.
/// </para>
/// <para>
/// Сложность: в среднем O(n log n), в худшем (например, на уже отсортированных данных
/// при неудачном выборе опорного) — O(n²). Память: O(log n) на стек рекурсии.
/// Устойчивость: неустойчива — обмен через весь массив меняет взаимный порядок равных.
/// </para>
/// </remarks>
public static class QuickSortAlgorithm
{
    /// <summary>Выполняет сортировку, записывая каждый шаг в трассировщик.</summary>
    public static void Run(SortTracer tracer)
    {
        int n = tracer.Length;

        if (n < 2)
        {
            tracer.MarkAllSorted("Массив из одного элемента уже упорядочен.");
            return;
        }

        tracer.Note("Быстрая сортировка Хоара: делим массив опорным элементом на «меньшие» и «большие» части.");

        SortRange(tracer, 0, n - 1);
        tracer.ClearRange();
        tracer.MarkAllSorted("Готово! Все части отсортированы, массив упорядочен по возрастанию.");
    }

    /// <summary>Рекурсивно сортирует участок массива от lo до hi.</summary>
    private static void SortRange(SortTracer tracer, int lo, int hi)
    {
        // Пустой участок сортировать нечего.
        if (lo > hi) return;

        // Один элемент — он уже стоит на своём месте.
        if (lo == hi)
        {
            tracer.MarkSorted(lo, $"В части остался один элемент {tracer.ValueAt(lo)} — он уже на своём месте.");
            return;
        }

        tracer.SetRange(lo, hi);
        tracer.Note($"Сортируем часть массива с позиции {lo} по {hi} — всего {hi - lo + 1} элементов.");

        // Делим участок: получаем границу между «меньшими» и «большими».
        int split = Partition(tracer, lo, hi);
        tracer.ClearPivot();
        tracer.Note($"Раздел прошёл по границе {split}: слева элементы не больше опорного, справа — не меньше.");

        // Левая часть — от lo до split, правая — от split+1 до hi.
        SortRange(tracer, lo, split);

        // Возвращаем подсветку на исходный участок, чтобы было видно, где мы находимся.
        tracer.SetRange(lo, hi);
        SortRange(tracer, split + 1, hi);
        tracer.ClearRange();
    }

    /// <summary>
    /// Разделение по Хоару. Возвращает правый указатель — границу раздела.
    /// </summary>
    /// <remarks>
    /// Границы массива можно не проверять: опорным выбран самый левый элемент,
    /// и он всё время остаётся внутри участка, поэтому указатель i остановится
    /// не позже него, а указатель j — не раньше. Этот элемент работает «часовым».
    /// </remarks>
    private static int Partition(SortTracer tracer, int lo, int hi)
    {
        int pivot = tracer.MarkPivot(lo,
            $"Опорный элемент — {tracer.ValueAt(lo)} (позиция {lo}). С ним будем сравнивать остальные.");

        // i идёт слева, j — справа. Они стартуют «за пределами» участка,
        // потому что в цикле сначала выполняется шаг, а потом проверка.
        int i = lo - 1;
        int j = hi + 1;

        while (true)
        {
            // Ищем слева элемент, который не меньше опорного.
            do
            {
                i++;
            }
            while (tracer.IsBelowPivot(i,
                $"Слева: элемент {tracer.ValueAt(i)} на позиции {i} меньше опорного {pivot} — идём дальше вправо."));

            // Ищем справа элемент, который не больше опорного.
            do
            {
                j--;
            }
            while (tracer.IsAbovePivot(j,
                $"Справа: элемент {tracer.ValueAt(j)} на позиции {j} больше опорного {pivot} — идём дальше влево."));

            // Указатели встретились — участок разделён.
            if (i >= j)
            {
                tracer.Note($"Указатели встретились (i = {i}, j = {j}) — деление закончено.");
                return j;
            }

            // Слева найден «большой», справа — «маленький». Меняем их местами.
            tracer.Swap(i, j,
                $"{tracer.ValueAt(i)} стоит слева и не меньше опорного, а {tracer.ValueAt(j)} справа и не больше — меняем их местами.");
        }
    }

    /// <summary>
    /// Быстрая версия без трассировки — для замеров времени.
    /// Алгоритм тот же: разделение Хоара и рекурсивная обработка частей.
    /// </summary>
    public static void Sort(int[] data) => Sort(data, 0, data.Length - 1);

    private static void Sort(int[] data, int lo, int hi)
    {
        if (lo >= hi) return;

        int split = Partition(data, lo, hi);
        Sort(data, lo, split);
        Sort(data, split + 1, hi);
    }

    private static int Partition(int[] data, int lo, int hi)
    {
        int pivot = data[lo];
        int i = lo - 1;
        int j = hi + 1;

        while (true)
        {
            do { i++; } while (data[i] < pivot);
            do { j--; } while (data[j] > pivot);

            if (i >= j) return j;

            (data[i], data[j]) = (data[j], data[i]);
        }
    }
}
