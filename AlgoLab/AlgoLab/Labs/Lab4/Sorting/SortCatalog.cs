using AlgoLab.Models;

namespace AlgoLab.Labs.Lab4.Sorting;

/// <summary>
/// Описание одной демонстрации сортировки: всё, что нужно и для карточки в каталоге,
/// и для страницы демонстрации, и для таблицы в отчёте.
/// </summary>
public sealed class SortDemoInfo
{
    /// <summary>Идентификатор в адресе страницы.</summary>
    public string Slug { get; init; } = "";

    /// <summary>Название алгоритма.</summary>
    public string Name { get; init; } = "";

    /// <summary>Короткое описание для карточки.</summary>
    public string Description { get; init; } = "";

    /// <summary>Итоговая сложность для бейджа.</summary>
    public string Complexity { get; init; } = "";

    /// <summary>Вид сложности для графиков и фильтров.</summary>
    public ComplexityType ComplexityType { get; init; }

    /// <summary>Оценка дополнительной памяти.</summary>
    public string Memory { get; init; } = "";

    /// <summary>Устойчивость словами.</summary>
    public string Stability { get; init; } = "";

    /// <summary>Устойчив ли алгоритм.</summary>
    public bool IsStable { get; init; }

    /// <summary>Лучший случай.</summary>
    public string BestCase { get; init; } = "";

    /// <summary>Средний случай.</summary>
    public string AverageCase { get; init; } = "";

    /// <summary>Худший случай.</summary>
    public string WorstCase { get; init; } = "";

    /// <summary>Группа: квадратичные или усовершенствованные.</summary>
    public string Category { get; init; } = "";

    /// <summary>Короткая формула-подсказка для карточки.</summary>
    public string Formula { get; init; } = "";

    /// <summary>Объяснение «для шестиклассника».</summary>
    public string Idea { get; init; } = "";

    /// <summary>Разбор алгоритма по шагам для страницы и отчёта.</summary>
    public string[] Walkthrough { get; init; } = Array.Empty<string>();

    /// <summary>Запуск с трассировкой (пишет шаги в лог).</summary>
    public Action<SortTracer> Run { get; init; } = _ => { };

    /// <summary>Запуск без трассировки (для замеров времени).</summary>
    public Action<int[]> FastSort { get; init; } = _ => { };
}

